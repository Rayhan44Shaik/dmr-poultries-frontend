        incentives: money(r, 0, 6000, 100),
        fuelAllowance: emp.department === "Driver" ? money(r, 500, 2500, 100) : 0,
        nightAllowance: ["Driver", "Supervisor", "Helper"].includes(emp.department)
          ? money(r, 0, 2000, 100)
          : 0,
        leaveDeduction: 0,
        advanceRecovery: 0,
        loanEMI: 0,
        latePenalty: 0,
        otherDeductions: 0,
        status: "Pending",
        paymentDate: null,
        paymentRef: null,
        paidAt: null,
        submittedAt: null,
        submittedBy: null,
