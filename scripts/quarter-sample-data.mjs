// 13. MASTERS PAGED ENVELOPE
// The Masters pages use useMasterRecords(), which calls the SAME master path
// with query params and expects a PAGED ENVELOPE — not a plain array:
//     { items: [...], total, page, facets: { city: [...], department: [...] } }
// (`data.items.map(...)` is called directly, so a bare array throws
//  "Cannot read properties of undefined (reading 'map')".)
// Every list endpoint below therefore returns the envelope whenever the request
// carries master query params, and a plain array otherwise — which is what the
// non-Masters consumers (dropdowns, Trip Entry, Orders, reports) still expect.
// ═══════════════════════════════════════════════════════════════════════════

/** True when the request came from useMasterRecords (it always sends page+pageSize). */
function isMasterQuery(params) {
  return params.has("page") && params.has("pageSize");
}

/** Field groups used for free-text search per master. */
const SEARCH_FIELDS = {
  shops: ["shopNumber", "shopName", "ownerName", "phoneNumber", "city", "village", "address", "email", "associationType"],
  employees: ["employeeNo", "employeeName", "department", "role", "phoneNumber", "email", "address", "licenseNumber"],
  farms: ["farmNo", "farmName", "ownerName", "supervisorName", "phoneNumber", "village", "address"],
  vehicles: ["vehicleNo", "vehicleNumber", "vehicleType", "trackingId", "fastagBank", "engineNumber", "chassisNumber"],
  banks: ["bankNo", "bankName", "branch", "accountNumber", "ifscCode", "upiId"],
  birdTypes: ["birdTypeNo", "birdType", "description"],
};

/** Sort keys the Masters toolbar offers: Number / Name / Status. */
const SORT_KEYS = {
  shops: { number: "shopNo", name: "shopName" },
  employees: { number: "employeeNo", name: "employeeName" },
  farms: { number: "farmNo", name: "farmName" },
  vehicles: { number: "vehicleNo", name: "vehicleNumber" },
  banks: { number: "bankNo", name: "bankName" },
  birdTypes: { number: "birdTypeNo", name: "birdType" },
};

/** Distinct, trimmed, case-collapsed facet values (first spelling wins). */
function facetValues(rows, field) {
  const seen = new Map();
  for (const row of rows) {
    const raw = String(row[field] ?? "").trim();
    if (!raw) continue;
    const key = raw.toLowerCase();
    if (!seen.has(key)) seen.set(key, raw);
  }
  return [...seen.values()].sort((a, b) => a.localeCompare(b));
}

/**
 * Build the Masters paged envelope: filter → facet → sort → paginate.
 * `export=true` returns every matching row (the toolbar's Export action).
 */
function masterEnvelope(kind, allRows, params) {
  const search = (params.get("search") || "").trim().toLowerCase();
  const status = (params.get("status") || "").trim();
  const city = (params.get("city") || "").trim();
  const department = (params.get("department") || "").trim();
  const sort = params.get("sort") || "number";
  const direction = (params.get("direction") || "asc").toLowerCase();

  let rows = allRows.slice();
  if (search) {
    const fields = SEARCH_FIELDS[kind] ?? [];
    rows = rows.filter((row) =>
      fields.some((f) => String(row[f] ?? "").toLowerCase().includes(search))
    );
  }
  if (status) rows = rows.filter((row) => String(row.status ?? "") === status);
  if (city) {
    rows = rows.filter(
      (row) =>
        String(row.city ?? "").toLowerCase() === city.toLowerCase() ||
        String(row.village ?? "").toLowerCase() === city.toLowerCase()
    );
  }
  if (department) rows = rows.filter((row) => String(row.department ?? "") === department);

  // Facets describe the WHOLE master (so the dropdowns never collapse to the
  // current page), which is what the Shops city / Employees department
  // selectors read.
  const facets = {
    city: facetValues(allRows, "city"),
    village: facetValues(allRows, "village"),
    department: facetValues(allRows, "department"),
    role: facetValues(allRows, "role"),
    status: facetValues(allRows, "status"),
    associationType: facetValues(allRows, "associationType"),
    vehicleType: facetValues(allRows, "vehicleType"),
  };

  const keys = SORT_KEYS[kind] ?? {};
  const sortField = sort === "status" ? "status" : keys[sort] ?? keys.number;
  rows.sort((a, b) => {
    const av = a[sortField];
    const bv = b[sortField];
    const cmp =
      typeof av === "number" && typeof bv === "number"
        ? av - bv
        : String(av ?? "").localeCompare(String(bv ?? ""));
    return direction === "desc" ? -cmp : cmp;
  });

  const total = rows.length;
  if (String(params.get("export")) === "true") {
    return { items: rows, total, page: 1, facets };
  }
  const pageSize = Math.max(1, Number(params.get("pageSize")) || 10);
  const totalPages = Math.max(1, Math.ceil(total / pageSize));
  const page = Math.min(Math.max(1, Number(params.get("page")) || 1), totalPages);
  return {
    items: rows.slice((page - 1) * pageSize, page * pageSize),
    total,
    page,
    pageSize,
    totalPages,
    facets,
  };
}

/** Serve a master list as an envelope for Masters pages, array for everyone else. */
function serveMaster(kind, rows, params) {
  return isMasterQuery(params) || params.get("export") === "true"
    ? masterEnvelope(kind, rows, params)
    : rows;
}

