/** The automatic duty a department maps to on a given date. */
function automaticDutyType(employee, date) {
  if (isSunday(date)) return "WeeklyOff";
  if (employee.department === "Driver") return "Driver";
  if (["Supervisor", "Helper", "Loader"].includes(employee.department)) return "Delivery";
  if (employee.department === "Collection") return "Collection";
  if (employee.department === "Mechanic") return "Repair";
  return "Office";
}

function onApprovedDutyLeave(employeeId, date) {
  return LEAVES.some(
    (l) => l.status === "Approved" && l.employeeId === employeeId && l.fromDate <= date && l.toDate >= date
  );
}

/** AutoPlan: every still-unassigned cell of the week with its proposal. */
function dutyAutoPlan(weekStart) {
  const start = weekStart || CURRENT_WEEK_START;
  const days = Array.from({ length: 7 }, (_, i) => addDays(start, i));
  const employees = EMPLOYEES.filter((e) => e.status === "Active");
  const rows = [];
  for (const emp of employees) {
    for (const date of days) {
      const assigned = (DUTY_BY_DATE.get(date) ?? []).some((a) => a.employeeId === emp.id);
      if (assigned || onApprovedDutyLeave(emp.id, date)) continue;
      const dutyType = automaticDutyType(emp, date);
      const vehicle =
        dutyType === "Driver"
          ? ACTIVE_VEHICLES[(emp.id + seedOf(date)) % ACTIVE_VEHICLES.length]
          : null;
      rows.push({
        employeeId: emp.id,
        employeeName: emp.employeeName,
        department: emp.department,
        role: emp.role,
        date,
        dutyType,
        vehicleId: vehicle?.id ?? null,
        vehicleNo: vehicle?.vehicleNumber ?? null,
        proposed: true,
      });
    }
  }
  const count = (type) => rows.filter((r) => r.dutyType === type).length;
  const saturday = days[5];
  const satAssigned = (DUTY_BY_DATE.get(saturday) ?? []).filter(
    (a) => !["WeeklyOff", "Rest"].includes(a.dutyType)
  );
  const required = 86; // Driver 20 + Supervisor 18 + Helper 20 + Loader 16 + Collector 12
  return {
    employeesAffected: new Set(rows.map((r) => r.employeeId)).size,
    delivery: count("Delivery"),
    repair: count("Repair"),
    office: count("Office"),
    collection: count("Collection"),
    weeklyOff: count("WeeklyOff"),
    saturdayRequired: required,
    saturdayAssigned: satAssigned.length,
    saturdayShortage: Math.max(0, required - satAssigned.length),
    conflicts: [],
    rows,
  };
}

