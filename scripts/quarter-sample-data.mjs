/** Recompute gross / deductions / net from the submitted components. */
function recomputeSalary(row) {
  row.totalGross =
    (row.basicSalary ?? 0) + (row.overtime ?? 0) + (row.incentives ?? 0) +
    (row.fuelAllowance ?? 0) + (row.nightAllowance ?? 0);
  row.totalDeductions =
    (row.leaveDeduction ?? 0) + (row.advanceRecovery ?? 0) + (row.loanEMI ?? 0) +
    (row.latePenalty ?? 0) + (row.otherDeductions ?? 0);
  row.netSalary = round(row.totalGross - row.totalDeductions, 2);
  return row;
}

/** Upsert a salary row keyed on (employeeId, month) — the review-modal edit. */
function upsertSalaryRow(body) {
  const employeeId = Number(body.employeeId);
  const month = String(body.month ?? CURRENT_MONTH);
  let row = SALARIES.find((s) => s.employeeId === employeeId && s.month === month);
  if (!row) {
    const emp = EMP_BY_ID.get(employeeId);
    row = {
      id: String(nextNumericId(SALARIES)),
      employeeId,
      employeeNo: emp?.employeeNo ?? employeeId,
      employeeName: emp?.employeeName ?? "",
      department: emp?.department ?? "",
      role: emp?.role ?? "",
      month,
      status: "Pending",
      createdAt: nowIso(),
    };
    SALARIES.push(row);
  }
  for (const key of [
    "employeeName", "department", "role", "basicSalary", "overtime", "incentives",
    "fuelAllowance", "nightAllowance", "leaveDeduction", "advanceRecovery",
    "loanEMI", "latePenalty", "otherDeductions", "status",
  ]) {
    if (body[key] != null) row[key] = body[key];
  }
  row.paymentDate = body.paymentDate ?? row.paymentDate ?? null;
  recomputeSalary(row);
  row.monthClosed = row.month !== CURRENT_MONTH;
  row.updatedAt = nowIso();
  return row;
}

/** Generate the salary register for a month that has no rows yet. */
function generateSalaryMonth(month) {
  const existing = SALARIES.filter((s) => s.month === month);
  const employees = EMPLOYEES.filter((e) => e.status === "Active");
  const skipped = existing.length;
  let generated = 0;
  if (existing.length === 0) {
    const monthDates = DATES.filter((d) => monthOf(d) === month);
    for (const emp of employees) {
      const r = rng(15500 + seedOf(month) + emp.id);
      const workingDays = Math.max(1, monthDates.filter((d) => !isSunday(d)).length);
      const row = {
        id: String(nextNumericId(SALARIES)),
        employeeId: emp.id,
        employeeNo: emp.employeeNo,
        employeeName: emp.employeeName,
        department: emp.department,
        role: emp.role,
        month,
        basicSalary: emp.salary,
        overtime: money(r, 0, 4500, 100),
        incentives: money(r, 0, 6000, 100),
        fuelAllowance: emp.department === "Driver" ? money(r, 500, 2500, 100) : 0,
        nightAllowance: ["Driver", "Supervisor", "Helper"].includes(emp.department)
          ? money(r, 0, 2000, 100)
          : 0,
        leaveDeduction: 0,
        advanceRecovery: 0,
        loanEMI: 0,
        latePenalty: 0,
        otherDeductions: 0,
        status: "Pending",
        paymentDate: null,
        paymentRef: null,
        paidAt: null,
        submittedAt: null,
        submittedBy: null,
        createdAt: nowIso(),
        workingDays,
        presentDays: workingDays,
        leaveDays: 0,
        weeklyOffDays: monthDates.length - workingDays,
        monthClosed: month !== CURRENT_MONTH,
        correctionWindowDaysRemaining: month === CURRENT_MONTH ? 10 : 0,
      };
      SALARIES.push(recomputeSalary(row));
      generated += 1;
    }
  }
  return { month, requested: employees.length, generated, skippedExisting: skipped };
}

