      totalBirds: stage >= 3 ? totalBirds : 0,
      boxes: stage >= 3 ? boxes : 0,
      avgWeight: stage >= 3 ? avgWeight : 0,
      pickupLoadTime: stage >= 3 ? ts(date, "08:40:00") : "",
      pickupStepSubmitted: stage >= 3,
