// ── Shop ledger rows (sales debit / collections credit, running balance) ────
function buildLedger(shopId) {
  const rows = [];
  for (const s of SHOP_SALES) {
    if (shopId && s.shopId !== shopId) continue;
    rows.push({
      id: s.id,
      shopId: s.shopId,
      shopName: s.shopName,
      date: s.tripDate,
      type: "sale",
      referenceType: "shop_sale",
      referenceId: s.id,
      referenceNo: s.saleNo,
      description: `Sale — ${s.birdType} ${s.totalBirds} birds / ${s.totalWeight} kg`,
      debit: s.amount,
      credit: 0,
      balance: 0,
      birds: s.totalBirds,
      weight: s.totalWeight,
      rate: s.rate ?? 0,
      paymentMode: null,
      status: s.status,
      createdAt: s.createdAt,
    });
  }
  for (const c of COLLECTIONS) {
    if (shopId && c.shopId !== shopId) continue;
    if (c.status !== "Approved") continue;
    rows.push({
      id: 900000 + c.id,
      shopId: c.shopId,
      shopName: c.shopName,
      date: c.collectionDate,
      type: "collection",
      referenceType: "collection_entry",
      referenceId: c.id,
      referenceNo: c.collectionNo,
      description: `Collection — ${c.paymentMode}${c.referenceNo ? ` (${c.referenceNo})` : ""}`,
      debit: 0,
      credit: c.amount,
      balance: 0,
      birds: 0,
      weight: 0,
      rate: 0,
      paymentMode: c.paymentMode,
      status: "Approved",
      createdAt: c.createdAt,
    });
  }
  rows.sort((a, b) => a.date.localeCompare(b.date) || a.id - b.id);
  let running = shopId ? SHOP_BY_ID.get(shopId)?.openingBalance ?? 0 : 0;
  for (const row of rows) {
    running = round(running + row.debit - row.credit, 2);
    row.balance = running;
  }
  return rows;
}

