/** Mulberry32 — deterministic PRNG keyed by any integer seed. */
function rng(seed) {
  let s = (seed >>> 0) || 1;
  return () => {
    s = (s + 0x6d2b79f5) >>> 0;
    let t = Math.imul(s ^ (s >>> 15), 1 | s);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
const pick = (r, arr) => arr[Math.floor(r() * arr.length) % arr.length];
const between = (r, lo, hi) => lo + Math.floor(r() * (hi - lo + 1));
const money = (r, lo, hi, step = 50) =>
  Math.round(between(r, lo, hi) / step) * step;
const seedOf = (s) => Number(String(s).replace(/\D/g, "").slice(-9) || 1);

